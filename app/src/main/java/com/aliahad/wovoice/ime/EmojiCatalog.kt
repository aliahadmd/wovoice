/**
 * Pure most-recently-used bookkeeping for the emoji page's Recents row.
 * Kept free of Android types so it is directly unit-testable.
 */
object EmojiRecents {

    const val DEFAULT_CAP = 32

    fun updated(recents: List<String>, emoji: String, cap: Int = DEFAULT_CAP): List<String> {
        require(cap > 0)
        val cleaned = emoji.trim()
        if (cleaned.isEmpty()) return recents.take(cap)
        return (listOf(cleaned) + recents.filter { it != cleaned }).take(cap)
    }
}
